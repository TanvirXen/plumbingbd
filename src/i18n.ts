/** Prefix a site path with /bn for Bangla. */
export const lp = (lang: Lang, path: string) => (lang === "bn" ? `/bn${path === "/" ? "/" : path}` : path);

const bnDigits = "০১২৩৪৫৬৭৮৯";
export const num = (lang: Lang, n: number | string) => {
  const s = typeof n === "number" ? n.toLocaleString("en-IN") : n;
  return lang === "bn" ? s.replace(/\d/g, (d) => bnDigits[+d]) : s;
};

